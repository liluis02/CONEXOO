    private void btnSalvarPerfilEmpresaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarPerfilEmpresaActionPerformed
        
    String razaoSocial = txtRazaoSocial1.getText().trim();
    String nomeFantasia = txtNomeFantasia.getText().trim();
    String cnpj = txtCNPJ.getText().replaceAll("\\D", "");
    String telefone = txtTelefoneComercial.getText().replaceAll("\\D", "");
    String cidade = txtCidadeEmpresa.getText().trim();
    String descricao = txtDescricaoEmpresa.getText().trim();

    String estado = cmbEstadoEmpresa.getSelectedItem().toString();
    String porte = cmbPortedaEmpresa.getSelectedItem().toString();
    String areaAtuacao = cmbAreaAtuacaoEmpresa.getSelectedItem().toString();

    // Validar razão social
    if (razaoSocial.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Preencha a razão social da empresa!"
        );
        txtRazaoSocial1.requestFocus();
        return;
    }

    // Validar nome fantasia
    if (nomeFantasia.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Preencha o nome fantasia da empresa!"
        );
        txtNomeFantasia.requestFocus();
        return;
    }

    // Validar CNPJ
    if (cnpj.length() != 14) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Preencha o CNPJ corretamente!"
        );
        txtCNPJ.requestFocus();
        return;
    }

    // Validar telefone
    if (telefone.length() != 11) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Preencha o telefone comercial corretamente!"
        );
        txtTelefoneComercial.requestFocus();
        return;
    }

    // Validar cidade
    if (cidade.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Informe a cidade da empresa!"
        );
        txtCidadeEmpresa.requestFocus();
        return;
    }

    // Validar estado
    if (cmbEstadoEmpresa.getSelectedIndex() == 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Selecione o estado da empresa!"
        );
        cmbEstadoEmpresa.requestFocus();
        return;
    }

    // Validar porte
    if (cmbPortedaEmpresa.getSelectedIndex() == 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Selecione o porte da empresa!"
        );
        cmbPortedaEmpresa.requestFocus();
        return;
    }

    // Validar área de atuação
    if (cmbAreaAtuacaoEmpresa.getSelectedIndex() == 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Selecione a área de atuação da empresa!"
        );
        cmbAreaAtuacaoEmpresa.requestFocus();
        return;
    }
    
    if (salvarDadosEmpresa()) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Perfil da empresa salvo com sucesso!"
    );

    Menu_Frame menu = new Menu_Frame(idUsuario, "EMPRESA");
    menu.setVisible(true);
    this.dispose();
}
    }//GEN-LAST:event_btnSalvarPerfilEmpresaActionPerformed

