    private void btnSalvarSenhaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarSenhaActionPerformed
        String novaSenha = new String(txtNovaSenha.getPassword());
        String confirmarSenha = new String(txtConfirmarSenha.getPassword());

if (novaSenha.isEmpty() && confirmarSenha.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Preencha os campos de senha!");
    return;
}

if (novaSenha.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Digite sua nova senha!");
    return;
}

if (confirmarSenha.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Confirme sua nova senha!");
    return;
}

if (!novaSenha.equals(confirmarSenha)) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "As senhas não coincidem!");
    return;
}

if (novaSenha.length() < 8) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "A nova senha deve ter pelo menos 8 caracteres!");
    return;
}
String novoCodigo = CodigoRecuperacao.gerarCodigo();

String sql = "UPDATE usuarios "
           + "SET senha = ?, codigo_recuperacao = ? "
           + "WHERE id = ? AND codigo_recuperacao IS NOT NULL";

try (java.sql.Connection conexao = Conexao.conectar();
     java.sql.PreparedStatement stmt = conexao.prepareStatement(sql)) {

     stmt.setString(1, novaSenha);
     stmt.setString(2, novoCodigo);
     stmt.setInt(3, idUsuario);

    int linhasAtualizadas = stmt.executeUpdate();

    if (linhasAtualizadas > 0) {

javax.swing.JOptionPane.showMessageDialog(this,
        "Senha redefinida com sucesso!\n\n"
        + "Seu novo código de recuperação é: " + novoCodigo
        + "\n\nGuarde esse código em um lugar seguro!");

        new Login_Frame().setVisible(true);
        this.dispose();

    } else {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Não foi possível redefinir a senha. "
                + "Solicite um novo código de recuperação.");

    }

} catch (java.sql.SQLException e) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Erro ao redefinir a senha: " + e.getMessage());

}
    }//GEN-LAST:event_btnSalvarSenhaActionPerformed

