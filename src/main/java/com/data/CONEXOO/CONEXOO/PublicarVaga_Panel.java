private void carregarDadosVaga() {
    String sql = "SELECT * FROM vagas WHERE id_vaga = ?";

    try (java.sql.Connection conexao = Conexao.conectar();
         java.sql.PreparedStatement stmt = conexao.prepareStatement(sql)) {

        stmt.setInt(1, idVagaEdicao);

        try (java.sql.ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                txtTituloVaga.setText(rs.getString("titulo"));
                txtLocalizacao.setText(rs.getString("localizacao"));
                txtDescricaoVaga.setText(rs.getString("descricao"));

                cmbModalidadeVaga.setSelectedItem(
                    rs.getString("modelo_trabalho")
                );

                cmbTipoContrato.setSelectedItem(
                    rs.getString("tipo_contrato")
                );

                java.math.BigDecimal salarioMin =
                    rs.getBigDecimal("salario_min");

                java.math.BigDecimal salarioMax =
                    rs.getBigDecimal("salario_max");

                txtSalarioMin.setText(
                    salarioMin != null ? salarioMin.toPlainString() : ""
                );

                txtSalarioMax.setText(
                    salarioMax != null ? salarioMax.toPlainString() : ""
                );
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Erro ao carregar vaga: " + e.getMessage()
        );
    }
}
