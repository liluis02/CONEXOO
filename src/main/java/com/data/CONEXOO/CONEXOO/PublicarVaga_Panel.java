private void salvarVaga() {
    if (idVagaEdicao != -1) {
    atualizarVaga();
    return;
}

    String titulo = txtTituloVaga.getText().trim();
    String localizacao = txtLocalizacao.getText().trim();
    String descricao = txtDescricaoVaga.getText().trim();

    String modalidade = cmbModalidadeVaga
            .getSelectedItem().toString();

    String tipoContrato = cmbTipoContrato
            .getSelectedItem().toString();

    // Verifica os campos obrigatórios
    if (titulo.isEmpty() || localizacao.isEmpty()
            || descricao.isEmpty()
            || txtSalarioMin.getText().trim().isEmpty()
            || txtSalarioMax.getText().trim().isEmpty()
            || cmbModalidadeVaga.getSelectedIndex() == 0
            || cmbTipoContrato.getSelectedIndex() == 0) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Preencha todos os campos obrigatórios!"
        );
        return;
    }

    java.math.BigDecimal salarioMin;
    java.math.BigDecimal salarioMax;

    try {
        salarioMin = new java.math.BigDecimal(
                txtSalarioMin.getText().trim().replace(",", ".")
        );

        salarioMax = new java.math.BigDecimal(
                txtSalarioMax.getText().trim().replace(",", ".")
        );

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Digite valores válidos para os salários!"
        );
        return;
    }

    if (salarioMin.signum() < 0
            || salarioMax.compareTo(salarioMin) < 0) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "O salário máximo deve ser maior ou igual ao mínimo, "
                + "e os valores não podem ser negativos!"
        );
        return;
    }

    String sqlEmpresa =
            "SELECT id_empresa FROM empresas WHERE id_usuario = ?";

    String sqlVaga =
            "INSERT INTO vagas "
            + "(id_empresa, titulo, descricao, localizacao, "
            + "modelo_trabalho, tipo_contrato, salario_min, salario_max) "
            + "VALUES (?, ?, ?, ?, ?, ?, ?, ?)";

    try (java.sql.Connection conexao = Conexao.conectar()) {

        int idEmpresa;

        // Identifica a empresa logada
        try (java.sql.PreparedStatement stmt =
                conexao.prepareStatement(sqlEmpresa)) {

            stmt.setInt(1, idUsuario);

            try (java.sql.ResultSet rs = stmt.executeQuery()) {

                if (!rs.next()) {
                    javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "Nenhum perfil de empresa encontrado!"
                    );
                    return;
                }

                idEmpresa = rs.getInt("id_empresa");
            }
        }

        // Cadastra a vaga
        try (java.sql.PreparedStatement stmt =
                conexao.prepareStatement(sqlVaga)) {

            stmt.setInt(1, idEmpresa);
            stmt.setString(2, titulo);
            stmt.setString(3, descricao);
            stmt.setString(4, localizacao);
            stmt.setString(5, modalidade);
            stmt.setString(6, tipoContrato);
            stmt.setBigDecimal(7, salarioMin);
            stmt.setBigDecimal(8, salarioMax);

            int linhas = stmt.executeUpdate();

if (linhas > 0) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Vaga publicada com sucesso!"
    );

    if (acaoPublicacaoConcluida != null) {
        acaoPublicacaoConcluida.run();
    }
}
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao publicar vaga: " + e.getMessage()
        );
    }
}

private void atualizarVaga() {

    String titulo = txtTituloVaga.getText().trim();
    String localizacao = txtLocalizacao.getText().trim();
    String descricao = txtDescricaoVaga.getText().trim();

    if (titulo.isEmpty() || localizacao.isEmpty()
            || descricao.isEmpty()
            || txtSalarioMin.getText().trim().isEmpty()
            || txtSalarioMax.getText().trim().isEmpty()
            || cmbModalidadeVaga.getSelectedIndex() == 0
            || cmbTipoContrato.getSelectedIndex() == 0) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Preencha todos os campos obrigatórios!"
        );
        return;
    }

    java.math.BigDecimal salarioMin;
    java.math.BigDecimal salarioMax;

    try {
        salarioMin = new java.math.BigDecimal(
                txtSalarioMin.getText().trim().replace(",", ".")
        );

        salarioMax = new java.math.BigDecimal(
                txtSalarioMax.getText().trim().replace(",", ".")
        );

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Digite valores válidos para os salários!"
        );
        return;
    }

    if (salarioMin.signum() < 0
            || salarioMax.compareTo(salarioMin) < 0) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Verifique os valores dos salários!"
        );
        return;
    }

    String sql = "UPDATE vagas SET titulo = ?, descricao = ?, "
            + "localizacao = ?, modelo_trabalho = ?, "
            + "tipo_contrato = ?, salario_min = ?, salario_max = ? "
            + "WHERE id_vaga = ? AND id_empresa IN "
            + "(SELECT id_empresa FROM empresas WHERE id_usuario = ?) "
            + "AND status = 'ATIVA'";

    try (java.sql.Connection conexao = Conexao.conectar();
         java.sql.PreparedStatement stmt =
                 conexao.prepareStatement(sql)) {

        stmt.setString(1, titulo);
        stmt.setString(2, descricao);
        stmt.setString(3, localizacao);
        stmt.setString(4, cmbModalidadeVaga.getSelectedItem().toString());
        stmt.setString(5, cmbTipoContrato.getSelectedItem().toString());
        stmt.setBigDecimal(6, salarioMin);
        stmt.setBigDecimal(7, salarioMax);
        stmt.setInt(8, idVagaEdicao);
        stmt.setInt(9, idUsuario);

        int linhas = stmt.executeUpdate();

        if (linhas > 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Vaga atualizada com sucesso!"
            );

            if (acaoPublicacaoConcluida != null) {
                acaoPublicacaoConcluida.run();
            }

        } else {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Não foi possível atualizar esta vaga."
            );
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Erro ao atualizar vaga: " + e.getMessage()
        );
    }
}



