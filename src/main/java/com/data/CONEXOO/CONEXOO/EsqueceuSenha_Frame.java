    private void btnContinuarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnContinuarActionPerformed
        String email = txtEmailRecuperacao.getText().trim();
String codigo = txtCodigoRecuperacao.getText().trim();

if (email.isEmpty() && codigo.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Preencha o e-mail e o código de recuperação!");
    return;
}

if (email.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Digite seu e-mail cadastrado!");
    return;
}

if (codigo.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Digite seu código de recuperação!");
    return;
}

if (codigo.length() != 8) {
    JOptionPane.showMessageDialog(this,
            "O código de recuperação deve ter 8 caracteres!");
    return;
}
String sql = "SELECT id FROM usuarios "
           + "WHERE email = ? AND codigo_recuperacao = ?";

try (java.sql.Connection conexao = Conexao.conectar();
     java.sql.PreparedStatement stmt = conexao.prepareStatement(sql)) {

    stmt.setString(1, email);
    stmt.setString(2, codigo);

    try (java.sql.ResultSet rs = stmt.executeQuery()) {

if (rs.next()) {

    int idUsuario = rs.getInt("id");

    JOptionPane.showMessageDialog(this,
            "Código de recuperação validado com sucesso!");

    new RedefinirSenha_Frame(idUsuario).setVisible(true);
    this.dispose();

} else {

    JOptionPane.showMessageDialog(this,
            "E-mail ou código de recuperação incorreto!");

}
    }

} catch (java.sql.SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Erro ao verificar o código: " + e.getMessage());
}
    }//GEN-LAST:event_btnContinuarActionPerformed

