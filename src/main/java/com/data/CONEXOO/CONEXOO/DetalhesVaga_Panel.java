private void carregarDetalhesVaga() {

    String sql = "SELECT v.*, e.nome_fantasia "
            + "FROM vagas v "
            + "INNER JOIN empresas e ON v.id_empresa = e.id_empresa "
            + "WHERE v.id_vaga = ?";

    try (java.sql.Connection conexao = Conexao.conectar();
         java.sql.PreparedStatement stmt =
                 conexao.prepareStatement(sql)) {

        stmt.setInt(1, idVaga);

        try (java.sql.ResultSet rs = stmt.executeQuery()) {

            if (rs.next()) {

                lblNomeVaga.setText(rs.getString("titulo"));
                lblNomeEmpresa.setText(rs.getString("nome_fantasia"));
                lblLocalizacao.setText(rs.getString("localizacao"));

                lblModalidade.setText(
                        "Modalidade: " + rs.getString("modelo_trabalho")
                );

                lblTipoContrato.setText(
                        "Contrato: " + rs.getString("tipo_contrato")
                );

                txtDescricaoDetalhes.setText(rs.getString("descricao"));
                txtDescricaoDetalhes.setCaretPosition(0);

                java.math.BigDecimal minimo =
                        rs.getBigDecimal("salario_min");

                java.math.BigDecimal maximo =
                        rs.getBigDecimal("salario_max");

                if (minimo != null && maximo != null) {
                    java.text.NumberFormat moeda =
                            java.text.NumberFormat.getCurrencyInstance(
                                    new java.util.Locale("pt", "BR")
                            );

                    lblSalario.setText(
                            moeda.format(minimo) + " até "
                            + moeda.format(maximo)
                    );
                } else {
                    lblSalario.setText("Salário a combinar");
                }

            } else {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "Vaga não encontrada!"
                );
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar detalhes da vaga: " + e.getMessage()
        );
    }
}


